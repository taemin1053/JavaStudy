package test;

import java.util.Arrays;
import java.util.PriorityQueue;

/* 코테 문제
하드디스크는 한 번에 하나의 작업만 수행할 수 있습니다.
 디스크 컨트롤러를 구현하는 방법은 여러 가지가 있습니다.
 이 문제에서는 우선순위 디스크 컨트롤러라는 가상의 장치를 이용한다고 가정
우선순위 디스크 컨트롤러 작동 방식
1. 어떤 작업 요청이 들어왔을 때 작업의 번호, 작업의 요청 시각, 작업의 소요 시간을 저장해 두는 대기 큐가 있습니다.
 처음에 이 큐는 비어있습니다.
2.디스크 컨트롤러는 하드디스크가 작업을 하고 있지 않고 대기 큐가 비어있지 않다면
 가장 우선순위가 높은 작업을 대기 큐에서 꺼내서 하드디스크에 그 작업을 시킵니다.
 이때, 작업의 소요시간이 짧은 것, 작업의 요청 시각이 빠른 것, 작업의 번호가 작은 것 순으로 우선순위가 높습니다.
하드디스크는 작업을 한 번 시작하면 작업을 마칠 때까지 그 작업만 수행합니다.
하드디스크가 어떤 작업을 마치는 시점과 다른 작업 요청이 들어오는 시점이 겹친다면 하드디스크가 작업을 마치자마자
디스크 컨트롤러는 요청이 들어온 작업을 대기 큐에 저장한 뒤 우선순위가 높은 작업을 대기 큐에서 꺼내서 하드디스크에 그 작업을 시킵니다.
또, 하드디스크가 어떤 작업을 마치는 시점에 다른 작업이 들어오지 않더라도 그 작업을 마치자마자 또 다른 작업을 시작할 수 있습니다. 이 과정에서 걸리는 시간은 없다고 가정합니다.

 문제 목표 : 모든 요청 작업의 반환 시간의 평균의 정수부분을 return

논리 설계
1.jobs을 미리 오름차순으로 정렬하고 우선순위 큐로 보낼것 그래야 내생각엔 우선 순위큐도 int[] 형식으로 들어가서 [n번,job[n]]으로 들어 갈 거 같음
-> 오류수정:
맞는점: 작업을 먼저 줄 세워두겠다는 발상
틀린점: 2차원 배열 jobs 이미[요청 시각, 소요 시간] 2개의 값을 가지고 있음, 문제에서 정답을 구할 때 쓴느 건 요청 시각과 소요 시간 뿐, 작업 번호 n번은 필요 없음
해결: jobs 자체를 요청 시각 기준으로 정렬(Arrays.sort)
2.우선순위 큐에 적재,for문으로 넣을 것이고 .offer(i,job[][]) -> 이거 이렇게 적재하면 안될 거 같은데 job이 이중배열이라서 i를 넣기가 애매한데
 2-1
틀린 점: 시작하자마 jobs의 모든 작업을 우선 순위 큐에 for문으로 다 넣어버리면 미래에 들어올 작업이 먼저 들어 올 수 있음
원인: 예를 들어 10초 뒤에 들어올 작업인데 소요 시간이 1초라는 이유로 0초 시점에 그 작업을 먼저 처리해버림
해결: 우선 순위 큐에 현재시각 >= 요청 시간을 만족하는 작업만 골라서 그때 그때 넣는다

2-2
틀린점: 세상에 .offer(i, jobs[][]) 문법은 없음
해결: PriorityQueue<int[]> pq = new PriorityQueue<>((a,b) -> a[1] - b[1]); 소요시간 job[1] 기준 오름차순
      데이터 넣기: pq.offer(jobs[i]); (배열 뭉치 [요청시각, 소요시각]
3.일단 적제 했다고 하고 대기 큐가 있다고 함 걍 ArrayList에서 대기 시켜놓고 정렬만 하고 대기큐에 넣어서 요청시간보고, 맨처음은 무조건 넣고 sum에 소요시간을 넣을건데 그냥 넣지말고 소요시간 - 요청시간으로 넣기
이때 큐 들어가는 수 count로 새고, double answer = sum/count; 그리고 answer 소수점 버리고..? int로형변환 return
틀린점 : 소요시간 - 요청시간 계산부분 틀림
이유: 요청부터 끝날 때까지 걸린 총시간 -> 작업이 실제로 끝난 시각 - 요청 시각
예시) 1초에 요청된 9초짜리 작업이 앞선 작업 때문에 기다리다가 8초에 시작해서 17초에 끝났다면
    걸린 시간 17- 1초 =16초
해결: currentTime += currentJob[1]로 작업이 끝난 시각을 먼저 더한뒤
    sum+= (currentTime - currentJob[0])

    수정된 핵심 논리 흐름 4단계
    1.jobs 원본 정렬: jobs 배열을 요청 시각(job[0]) 오름차순으로 정렬한다.
    2.대기 큐 적재 (while문): 현재 시각(currentTime) 이하에 요청된 작업들만 PriorityQueue에 차례대로 넣는다.
    3.작업 처리 vs 시간 점프:큐가 비어있지 않다면 -> 큐에서 하나 꺼내서 처리 (현재 시각 += 소요시간, 누적합 += 현재 시각 - 요청시각, 카운트++).
    4.큐가 비어있다면 (놀고 있음) -> 다음 작업의 요청 시각으로 현재 시각을 강제로 점프시킴.결과 반환: 누적합 / 전체 작업 수(jobs.length)
*/
public class testHard {
    public int solution(int[][] jobs){
        //1. 원본 정렬 요청 시각 기준으로 오름차순
        Arrays.sort(jobs, (a,b) -> a[0] - b[0]);
        //2 대기 큐 생성 원본에서 요청 시각기준으로 오름 차순을 했으니, 대기 큐에서 소요시각으로 오름차순 정렬
        PriorityQueue<int[]> pq = new PriorityQueue<>((a, b) -> a[1]-b[1]);
        int sum = 0; //모든 작업의 소요시간 총합
        int currentTime = 0; //현재 시점
        int jobIndex = 0; //job 배열의 인덱스
        int count = 0; //완료된 작업수

        while(count < jobs.length){
            //대기큐가 비어있는지 확인 비어있으면 jobs에서 하나를 넣는다
            // 틀림 -> 예외 케이스에서 시간 왜곡 버그 발생, 이유 ->
            // 1.시간 조건 무시:jobs[jobIndex]의 요청 시각이 currentTime보다 미래일 수 있음,
            // 예시 jobs[0] : [0,3] jobs[1]: [10,3] 비어있다고 바로넣으면 jobs[0]이 끝난시점 jobs[1]이 들어가 5초라고 나옴
            //2, 동시 유입 누락:currentTime이전에 이미 여러개의 요청이 들어왔을 수도 있음 비어있다고 하나만 넣으면 대기 요청들을 빠트리게 됨
            //해결: 현재 시점(currentTime)까지 들어온 모든 작업을 대기 큐에 적재한다
            while(jobIndex < jobs.length && currentTime >= jobs[jobIndex][0]){
                pq.offer(jobs[jobIndex]);
                jobIndex++;
            }
            //큐 상태에 따른 분기 처리 큐가 비어있으면 다음 작업 요청 시각으로 점프한다
            if(pq.isEmpty()){
                currentTime = jobs[jobIndex][0];
            }
            //작업 처리
            else {
                int[] currentJob = pq.poll();
                currentTime += currentJob[1]; //작업 완료 후 시간 갱신
                sum += (currentTime - currentJob[0]);//반환 시간 누적하기
                count++;
            }
        }
        return sum/jobs.length;

    }

    public static void main(String[] args) {
        testHard testhard = new testHard();
        int[][] arr = {{0,2},{10,2},{5,5},{1,5}, {6,9},{7,4},{1,6}};
        System.out.println(testhard.solution(arr));
    }
}
